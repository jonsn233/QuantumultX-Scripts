#!/usr/bin/env python3
"""Build Quantumult X remote rules bundle from reviewed local source lists."""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SOURCES = [
    "Rules/AI/OpenAI.list",
    "Rules/AI/Claude.list",
    "Rules/AI/Gemini.list",
    "Rules/Media/Streaming.list",
    "Rules/International/Platforms.list",
    "Rules/International/Social.list",
    "Rules/Direct/Apple-China.list",
]
TARGET = ROOT / "Rules/QX-V2.5-All-Rules.list"
VALID = re.compile(r"^(host|host-suffix),([^,\\s]+),([A-Za-z][A-Za-z0-9-]*)$")
HEADER = (
    "# Quantumult X V2.5 consolidated remote filter list\\n"
    "# AUTO-GENERATED by Tools/build_rules.py; edit the source modules instead.\\n"
    "# Explicit policy fields retained; do not set force-policy on this resource.\\n"
)
def build():
    seen = {}
    lines = [HEADER.rstrip(), ""]
    for path in SOURCES:
        source = ROOT / path
        if not source.is_file():
            raise ValueError(f"Missing source: {path}")
        lines.append(f"# Source: {path}")
        for number, raw in enumerate(source.read_text(encoding="utf-8").splitlines(), 1):
            rule = raw.strip()
            if not rule or rule.startswith("#"):
                continue
            match = VALID.fullmatch(rule)
            if not match:
                raise ValueError(f"Invalid QX rule: {path}:{number}: {rule}")
            rule_type, host, policy = match.groups()
            key = (rule_type, host.lower())
            if key in seen:
                if seen[key] != policy:
                    raise ValueError(f"Conflicting policy for {key}: {seen[key]} vs {policy}")
                continue
            seen[key] = policy
            lines.append(rule)
        lines.append("")
    if len(seen) < 108:
        raise ValueError(f"Unexpected rule count drop: {len(seen)} < 108")
    return "\\n".join(lines).replace("\\\\n", "\\n") + "\\n", len(seen)

if __name__ == "__main__":
    try:
        content, count = build()
        if "--check" in sys.argv:
            if not TARGET.exists() or TARGET.read_text(encoding="utf-8") != content:
                raise ValueError("Bundle is out of sync; run python3 Tools/build_rules.py")
            print(f"OK: {count} rules; bundle in sync")
        else:
            TARGET.write_text(content, encoding="utf-8")
            print(f"Published {count} rules to {TARGET.relative_to(ROOT)}")
    except ValueError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        sys.exit(1)
